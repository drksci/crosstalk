"""Translate the delay-tensor recurrence into an ngspice netlist.

The NumPy model advances the slot axis sequentially::

    state[s+1] = tanh( decay * state[s] + drive[s] * profile
                       + coupling(state[s], mask[:, s]) )

There is no time in the circuit, so each slot is unrolled into *space* as a
stage instead. Stage ``s`` reads the post-``tanh`` nodes of stage ``s-1`` and
drives its own post-``tanh`` node, so the whole batch and geometry collapse
into a single operating-point solve. Node ``q{b}_{w}_{s}`` therefore holds
``traces[b, w, s]``.

Every additive term lands on a summing node ``u{b}_{w}_{s}`` through a
voltage-controlled current source, with a ``1 ohm`` resistor to ground so that
the node voltage in volts is numerically the summed current in amps:

===========  ==========================================  =================
term         control node                                gain
===========  ==========================================  =================
decay        ``q{b}_{w}_{s-1}``                          ``loss.decay``
drive        ``d{b}_{s}``                                ``profile[w]``
left/right   ``q{b}_{w-1}_{s-1}`` / ``q{b}_{w+1}_{s-1}`` ``sigmoid(mask[w,s]) * base``
second n.    ``q{b}_{w-2}_{s-1}`` / ``q{b}_{w+2}_{s-1}`` ``sigmoid(mask[w,s]) * second``
additive m.  ``m{w}_{s}``                                ``1``
===========  ==========================================  =================

The VCCS must be written ``G 0 u <ctrl> 0 <gain>``: SPICE defines its current
as flowing *out of* the positive output terminal, so putting ``0`` first is
what injects current into ``u``. Stage 0 omits the decay and coupling terms
because there is no stage -1; the model starts from zeros, so ground is the
correct previous state.

Emitting text is the entire job of this module. It imports no SPICE binding,
so the GPL-licensed PySpice stack stays over in ``spice_runner.py`` and never
reaches ``delay_tensor``.
"""

from __future__ import annotations

import numpy as np

from delay_tensor.config import DelayTensorConfig


def state_node_name(batch: int, wire: int, slot: int) -> str:
    """ngspice node holding ``traces[batch, wire, slot]``."""
    return f"q{batch}_{wire}_{slot}"


def state_node_names(batch: int, wires: int, slots: int) -> list[str]:
    """Every state node in ``(b, w, s)`` order, ready to reshape."""
    return [
        state_node_name(b, w, s) for b in range(batch) for w in range(wires) for s in range(slots)
    ]


def drive_samples(config: DelayTensorConfig, waveforms: np.ndarray) -> np.ndarray:
    """Replicate ``DelayTensor.run``'s drive matrix: ``(batch, slots)``.

    An input longer than the slot window is truncated; a shorter one leaves
    the tail at zero drive, which is what the tensor does when the launch
    stops early.
    """
    x = np.asarray(waveforms, dtype=np.float64)
    if x.ndim != 2 or x.shape[0] < 1 or x.shape[1] < 1:
        raise ValueError(f"waveforms must be a non-empty 2-D array, got shape {x.shape}")

    slots = config.tensor.slots
    drive = np.zeros((x.shape[0], slots), dtype=np.float64)
    drive[:, : min(x.shape[1], slots)] = x[:, :slots]
    return drive


def build_netlist(
    config: DelayTensorConfig,
    waveforms: np.ndarray,
    masks: np.ndarray,
    profile: np.ndarray,
) -> str:
    """Render ``waveforms`` as a self-contained ngspice deck.

    ``masks`` and ``profile`` come from the live :class:`DelayTensor`, so the
    circuit and the reference model read the same tensor rather than two
    independently seeded draws.
    """
    config.validate()
    tensor = config.tensor
    coupling = config.coupling

    expected = (tensor.wires, tensor.slots)
    if np.shape(masks) != expected:
        raise ValueError(f"masks must be {expected}, got {np.shape(masks)}")
    if np.shape(profile) != (tensor.wires,):
        raise ValueError(f"profile must be ({tensor.wires},), got {np.shape(profile)}")

    drive = drive_samples(config, waveforms)
    batch = drive.shape[0]
    modulated = coupling.mask_mode == "modulated"
    base = coupling.neighbour_strength
    second = coupling.second_neighbour_strength

    lines = [
        "* delay-tensor equivalence bench -- generated by benches/netlist.py",
        f"* geometry {tensor.wires}w x {tensor.slots}s, batch {batch}, "
        f"mask_mode={coupling.mask_mode}",
        "* reltol tight: the network is purely algebraic, so the operating point",
        "* should converge to machine precision rather than the default 1e-3.",
        ".options reltol=1e-9 abstol=1e-15 vntol=1e-12 gmin=1e-14 chgtol=1e-15",
        "",
        "* held input sample for each (batch, slot)",
    ]
    for b in range(batch):
        for s in range(tensor.slots):
            lines.append(f"Vd_{b}_{s} d{b}_{s} 0 {_f(drive[b, s])}")

    if not modulated and coupling.mask_gain != 0.0:
        lines.append("* additive mask offsets, shared across the batch")
        for s in range(tensor.slots):
            for w in range(tensor.wires):
                lines.append(f"Vm_{w}_{s} m{w}_{s} 0 {_f(coupling.mask_gain * masks[w, s])}")

    lines.append("* one stage per slot: 1 ohm summing resistor, then the nonlinearity")
    for b in range(batch):
        for s in range(tensor.slots):
            for w in range(tensor.wires):
                lines.extend(_stage(b, w, s, config, masks, profile, modulated, base, second))

    lines.append(".end")
    return "\n".join(lines) + "\n"


def _stage(
    b: int,
    w: int,
    s: int,
    config: DelayTensorConfig,
    masks: np.ndarray,
    profile: np.ndarray,
    modulated: bool,
    base: float,
    second: float,
) -> list[str]:
    """Summing resistor plus every source feeding one (batch, wire, slot)."""
    u = f"u{b}_{w}_{s}"
    q = state_node_name(b, w, s)
    out = [f"R_{b}_{w}_{s} {u} 0 1"]

    # sigmoid folds into the coupling gains only in modulated mode; in additive
    # mode the mask rides on its own offset source instead.
    shape = 1.0 / (1.0 + float(np.exp(-masks[w, s]))) if modulated else 1.0

    if s > 0:
        prev = state_node_name(b, w, s - 1)
        out.append(f"Gdc_{b}_{w}_{s} 0 {u} {prev} 0 {_f(config.loss.decay)}")
        if w > 0:
            out.append(
                f"Gnl_{b}_{w}_{s} 0 {u} {state_node_name(b, w - 1, s - 1)} 0 {_f(shape * base)}"
            )
        if w + 1 < config.tensor.wires:
            out.append(
                f"Gnr_{b}_{w}_{s} 0 {u} {state_node_name(b, w + 1, s - 1)} 0 {_f(shape * base)}"
            )
        if second > 0.0:
            if w > 1:
                out.append(
                    f"Gn2l_{b}_{w}_{s} 0 {u} {state_node_name(b, w - 2, s - 1)} 0 "
                    f"{_f(shape * second)}"
                )
            if w + 2 < config.tensor.wires:
                out.append(
                    f"Gn2r_{b}_{w}_{s} 0 {u} {state_node_name(b, w + 2, s - 1)} 0 "
                    f"{_f(shape * second)}"
                )

    out.append(f"Gdr_{b}_{w}_{s} 0 {u} d{b}_{s} 0 {_f(profile[w])}")
    if not modulated and config.coupling.mask_gain != 0.0:
        out.append(f"Gmk_{b}_{w}_{s} 0 {u} m{w}_{s} 0 1")
    if config.nonlinearity.type == "tanh":
        out.append(f"B_{b}_{w}_{s} {q} 0 V=tanh(v({u}))")
    else:
        # identity: the stage is a unity buffer, still a separate node so the
        # state-node naming stays uniform across nonlinearity settings.
        out.append(f"B_{b}_{w}_{s} {q} 0 V=v({u})")
    return out


def _f(value: float) -> str:
    """Round-trip a double: ngspice parses with strtod, 17 sig digits is exact."""
    return f"{float(value):.17g}"
